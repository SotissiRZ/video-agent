export const getLang = () => (document.documentElement.lang === 'en' ? 'en' : 'fr');

export const t = (key, params = {}) => {
  const lang = getLang();
  const text = MESSAGES[lang][key] ?? MESSAGES.fr[key] ?? key;
  return text.replace(/\{(\w+)\}/g, (_, k) => (params[k] ?? `{${k}}`));
};

/** Translate the static markup: data-i18n (text), data-i18n-html, data-i18n-placeholder, data-i18n-title. */
export const applyTranslations = (root = document) => {
  root.querySelectorAll('[data-i18n]').forEach((el) => (el.textContent = t(el.dataset.i18n)));
  root.querySelectorAll('[data-i18n-html]').forEach((el) => (el.innerHTML = t(el.dataset.i18nHtml)));
  root.querySelectorAll('[data-i18n-placeholder]').forEach((el) => (el.placeholder = t(el.dataset.i18nPlaceholder)));
  root.querySelectorAll('[data-i18n-title]').forEach((el) => {
    el.title = t(el.dataset.i18nTitle);
    el.setAttribute('aria-label', el.title);
  });
};

